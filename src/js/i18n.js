export function t(key, params = {}) {
  let s = (dict[lang.value] || dict.en)[key];
  if (s === undefined) s = dict.en[key];
  if (Array.isArray(s)) return s;
  for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
